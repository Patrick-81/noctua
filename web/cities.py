def search_cities(query: str, limit: int = 10) -> list[dict]:
    """Search cities by name (case-insensitive substring match)."""
    q = query.lower().strip()
    if not q:
        return []
    results = []
    for name, (lat, lng, elev) in CITIES.items():
        if q in name.lower():
            results.append({
                "name": name,
                "latitude": float(lat),
                "longitude": float(lng),
                "elevation": elev,
            })
    results.sort(key=lambda c: (not c["name"].lower().startswith(q), c["name"]))
    return results[:limit]
